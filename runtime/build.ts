// Builds the sandbox runtime into dist/bundle.ts: the minified IIFE, the CSS
// with fonts inlined as data: URIs, and the runtime version. The host inlines
// these into each sandbox iframe's srcdoc (no network access inside).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { RUNTIME_VERSION } from './src/protocol';

const root = import.meta.dir;
const out = await Bun.build({ entrypoints: [join(root, 'src/entry.ts')], format: 'iife', minify: true, target: 'browser' });
if (!out.success) {
  for (const l of out.logs) console.error(l);
  process.exit(1);
}
const js = await out.outputs[0].text();

const font = (pkg: string, file: string) => readFileSync(join(root, 'node_modules/@fontsource', pkg, 'files', file)).toString('base64');
const faces = [
  ['Caveat', 'caveat', 'caveat-latin-500-normal.woff2', 500, 'normal'],
  ['Caveat', 'caveat', 'caveat-latin-600-normal.woff2', 600, 'normal'],
  ['EB Garamond', 'eb-garamond', 'eb-garamond-latin-400-normal.woff2', 400, 'normal'],
  ['EB Garamond', 'eb-garamond', 'eb-garamond-latin-400-italic.woff2', 400, 'italic'],
  ['EB Garamond', 'eb-garamond', 'eb-garamond-latin-500-normal.woff2', 500, 'normal'],
  ['EB Garamond', 'eb-garamond', 'eb-garamond-latin-600-normal.woff2', 600, 'normal'],
] as const;
const fontCss = faces
  .map(([fam, pkg, file, w, st]) => `@font-face{font-family:'${fam}';font-style:${st};font-weight:${w};font-display:block;src:url(data:font/woff2;base64,${font(pkg, file)}) format('woff2');}`)
  .join('\n');
const css = fontCss + '\n' + readFileSync(join(root, 'src/sandbox.css'), 'utf8');

if (js.includes('</script')) throw new Error('bundle contains </script');
mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(
  join(root, 'dist/bundle.ts'),
  `// generated by runtime/build.ts — do not edit\nexport const RUNTIME_VERSION = ${JSON.stringify(RUNTIME_VERSION)};\nexport const RUNTIME_JS = ${JSON.stringify(js)};\nexport const RUNTIME_CSS = ${JSON.stringify(css)};\n`
);
console.log(`runtime ${RUNTIME_VERSION}: js ${(js.length / 1024).toFixed(0)} KB, css ${(css.length / 1024).toFixed(0)} KB`);
